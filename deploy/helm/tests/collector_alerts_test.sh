#!/usr/bin/env zsh
# Offline PromQL behavior tests against the actual rendered collector template.
# Requires Helm, yq v4, Docker and the pinned Prometheus image already cached.
# ShellCheck has no zsh parser; only the directory lookup uses zsh expansion.
# shellcheck shell=bash
set -euo pipefail
umask 077

script_dir=${0:A:h}
chart_dir="$script_dir/../deckard"
prometheus_image='prom/prometheus@sha256:76947e7ef22f8a698fc638f706685909be425dbe09bd7a2cd7aca849f79b5f64'
for tool in helm yq docker; do
  command -v "$tool" >/dev/null || { print -u2 "missing dependency: $tool"; exit 1; }
done
# Colima shares /Users, not macOS's default /var/folders temporary directory.
task_os=$(uname -s)
if [[ "$task_os" == Darwin ]]; then
  temp_base="${DECKARD_ALERTS_TMPDIR:-$HOME/Library/Caches}"
else
  temp_base="${DECKARD_ALERTS_TMPDIR:-${TMPDIR:-/tmp}}"
fi
temp_base=${temp_base:A}
[[ -d "$temp_base" && "$temp_base" != *,* ]] || { print -u2 'invalid test temporary directory'; exit 1; }
task_tmp=$(mktemp -d "$temp_base/deckard-collector-alerts.XXXXXXXX")
[[ ${task_tmp:h} == "$temp_base" && ${task_tmp:t} == deckard-collector-alerts.???????? ]] || {
  print -u2 'refusing unexpected test temporary directory'
  exit 1
}
cleanup() {
  # Remove only the two exact files generated by this invocation, never a tree.
  local generated_file
  for generated_file in "$task_tmp/collectors-rules.yaml" "$task_tmp/collector-alerts.test.yaml"; do
    [[ ! -e "$generated_file" ]] || unlink "$generated_file"
  done
  rmdir -- "$task_tmp"
}
trap cleanup EXIT

helm template deckard "$chart_dir" --namespace deckard \
  --show-only templates/collectors-alerts.yaml \
  --set database.cnpg.enabled=true \
  --set collectors.enabled=true --set collectors.alerts.enabled=true \
  --set collectors.alerts.maxAgeSeconds=600 \
  --set collectors.ingest.image=ghcr.io/chainseer-xyz/deckard@sha256:aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa \
  --set collectors.ingest.tokenSecretRef.name=example-producer \
  --set-json 'collectors.jobs=[{"name":"tetragon-events","type":"tetragon","schedule":"*/5 * * * *","sensorNamespace":"tetragon","sensorSelector":"app.kubernetes.io/name=tetragon","clusterScope":"k8s:uid:00000000-0000-0000-0000-000000000001"}]' \
  | yq -e '.spec' - > "$task_tmp/collectors-rules.yaml"
cp "$script_dir/collector-alerts.test.yaml" "$task_tmp/collector-alerts.test.yaml"
# Fixtures contain no credentials. Allow the image's non-root UID to read them.
chmod 755 "$task_tmp"
chmod 644 "$task_tmp/collectors-rules.yaml" "$task_tmp/collector-alerts.test.yaml"
docker run --rm --pull=never --network none --read-only --cap-drop ALL \
  --security-opt no-new-privileges --tmpfs /tmp:rw,nosuid,nodev,size=64m \
  --mount "type=bind,src=$task_tmp,dst=/rules,readonly" --workdir /rules \
  --entrypoint /bin/promtool "$prometheus_image" test rules collector-alerts.test.yaml
